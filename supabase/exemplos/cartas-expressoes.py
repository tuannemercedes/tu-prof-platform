for idioma, dados in (("espanhol", ES), ("ingles", EN)):
    for cat, itens in dados.items():
        for i, (pt, alvo, dica) in enumerate(itens):
            rows.append(f"('{idioma}',{lit(cat)},{lit(pt)},{lit(alvo)},{lit(dica)},'expressao',{100+i})")
for idioma, itens in ERROS.items():
    for i, (inc, cor, ex, tipo) in enumerate(itens):
        rows.append(f"('{idioma}','Gestão de contas',{lit(inc)},{lit(cor)},{lit(ex)},'{tipo}',{i})")
sql = "insert into public.cartas (idioma, categoria, incorreta, correta, explicacao, tipo, ordem) values\n" + ",\n".join(rows) + ";"
open("/tmp/cartas/expressoes.sql", "w").write(sql)
